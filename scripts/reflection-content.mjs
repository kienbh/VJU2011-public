import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

export function parseReflectionContent(markdown){
 const blocks=markdown.replace(/\r\n/g,'\n').split(/^## (?=NT-\d+ — )/m).slice(1);
 return blocks.map(block=>{
  const [,id,title]=block.match(/^(NT-\d+) — (.+)/)||[];
  const field=name=>block.match(new RegExp(`\\*\\*(?:${name}):\\*\\* (.+)`))?.[1].trim()||'';
  const section=block.split('### Tư tưởng giáo dục\n')[1]?.split('### Suy ngẫm hôm nay')[0]||'';
  const content=section.split('\n').filter(l=>l.startsWith('>')).map(l=>l.replace(/^> ?/,'')).join('\n').trim();
  const status=field('Trạng thái');
  const entry={id,title,content,author:field('Tác giả tư tưởng|Tác giả'),source:field('Nguồn tham chiếu|Nguồn gốc|Nguồn').replace(/\*/g,''),type:field('Loại nội dung'),question:field('Câu hỏi suy ngẫm'),status,approved:status==='Đã duyệt nội dung'};
  if(!id||!title||!content||!entry.author||!entry.source||!entry.question||!status)throw Error(`Incomplete reflection ${id}`);
  return entry;
 });
}

// Explicit owner approval of this exact editorial snapshot, independent of the CMS.
// Future edits must be reviewed again; an ID alone cannot publish changed text.
export function approvedBoardEntries(markdown, approval){
 const entries=parseReflectionContent(markdown);
 const digest=createHash('sha256').update(markdown.replace(/\r\n/g,'\n')).digest('hex');
 const approvedSnapshot=approval.sha256===digest;
 return entries.filter(e=>e.approved||(approvedSnapshot&&approval.ids.includes(e.id))).map(e=>({...e,approved:true}));
}

if(process.argv[1]===fileURLToPath(import.meta.url)){
 const source=new URL('../content/reflections/goc-suy-ngam-nghe-thay.md',import.meta.url);
 const markdown=readFileSync(source,'utf8'),entries=parseReflectionContent(markdown);
 const approval=JSON.parse(readFileSync(new URL('../content/reflections/board-publication.json',import.meta.url),'utf8'));
 const approved=approvedBoardEntries(markdown,approval);
 if(new Set(entries.map(e=>e.id)).size!==entries.length)throw Error('Duplicate reflection IDs');
 for(const [name,list] of [['approved',approved],['preview',entries]]){
  writeFileSync(new URL(`../src/reflections/board-content-${name}.ts`,import.meta.url),`// Generated by scripts/reflection-content.mjs; edit the Markdown source.\nexport default ${JSON.stringify(list,null,2)};\n`);
 }
 console.log(`Prepared ${entries.length} reflections; ${approved.length} approved for the public board.`);
}
