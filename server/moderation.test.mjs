import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {createHash,randomUUID} from 'node:crypto';
import {DatabaseSync} from 'node:sqlite';
import {createAppServer} from './app.mjs';

test('SSO moderation grants, origin protection, revocation and real-only board',async t=>{
 const dir=await mkdtemp(path.join(tmpdir(),'vju-moderation-')),dbPath=path.join(dir,'qa.sqlite');
 const issuer='https://id.example.test',appOrigin='http://localhost:5173',adminToken='qa-only-'.repeat(8);
 let grants=[{issuer,subject:'owner',role:'admin'},{issuer,subject:'mod',role:'moderator'}];
 let server=createAppServer({dbPath,adminToken,seedSamples:true,logger:()=>{}});await new Promise(r=>server.listen(0,'127.0.0.1',r));await new Promise(r=>server.close(r));
 server=createAppServer({dbPath,adminToken,seedSamples:false,moderationGrants:()=>grants,logger:()=>{},ssoConfig:{issuer,clientId:'qa',clientSecret:'qa',jwtSecret:'qa'.repeat(32),appOrigin}});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 t.after(async()=>{await new Promise(r=>server.close(r));await rm(dir,{recursive:true,force:true});});
 const base='http://127.0.0.1:'+server.address().port,db=new DatabaseSync(dbPath);
 const cookies={};for(const subject of ['owner','mod','regular','expired']){const token=randomUUID();cookies[subject]='vju_session='+token;db.prepare('INSERT INTO garden_sessions VALUES(?,?,?,?,?)').run(createHash('sha256').update(token).digest('hex'),issuer,subject,'Same display name',Date.now()+(subject==='expired'?-1000:60000));}db.close();
 const call=async(route,who,body,origin=appOrigin)=>{const r=await fetch(base+route,{method:body?'POST':'GET',headers:{...(who?{Cookie:cookies[who]||who}:{}),...(origin?{Origin:origin}:{}),'Content-Type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,data:await r.json()};};
 assert.equal((await call('/api/admin/session','owner')).data.role,'admin');
 for(const who of [null,'regular','expired','vju_guest_active=1; vju_guest=owner'])assert.equal((await call('/api/admin/greetings',who)).status,401);
 assert.equal((await call('/api/admin/greetings','mod')).status,200);
 assert.equal((await call('/api/admin/feedback','mod')).status,200);
 assert.equal((await call('/api/admin/feedback','regular')).status,401);
 assert.equal((await call('/api/admin/settings','mod',{effectsEnabled:true})).status,403);
 assert.equal((await call('/api/admin/settings','owner',{effectsEnabled:true},null)).status,403);
 assert.equal((await call('/api/admin/settings','owner',{effectsEnabled:true},'https://evil.test')).status,403);
 assert.equal((await call('/api/admin/settings','owner',{effectsEnabled:true})).status,200);
 assert.equal((await call('/api/greetings')).data.greetings.length,0);
 assert.equal((await call('/api/greetings/board')).data.total,0);
 const sent=await fetch(base+'/api/greetings',{method:'POST',headers:{'Content-Type':'application/json','Idempotency-Key':randomUUID()},body:JSON.stringify({recipientId:'general',message:'A real QA message for moderation only.',signature:'QA',className:'',visibility:'public',gift:'flowers'})});
 const card=await sent.json();assert.equal(sent.status,201);
 assert.equal((await call('/api/admin/greetings/'+card.id+'/moderate','mod',{action:'approve'})).status,200);
 assert.equal((await call('/api/greetings/board')).data.total,1);
 assert.equal((await call('/api/admin/greetings/'+card.id+'/moderate','owner',{action:'reject'})).status,200);
 assert.equal((await call('/api/greetings')).data.greetings.length,0);
 const potResponse=await fetch(base+'/api/garden/pots',{method:'POST',headers:{Cookie:cookies.regular,Origin:appOrigin,'Content-Type':'application/json','Idempotency-Key':randomUUID()},body:JSON.stringify({flowers:['rose'],signature:'Original gardener',recipient:'Teachers',message:'Thank you for teaching us.'})});
 assert.equal(potResponse.status,201);const pot=(await potResponse.json()).pot;
 const gardenPath='/api/admin/greetings/'+pot.id;
 const listing=(await call('/api/admin/greetings?status=all','owner')).data.greetings;
 assert.deepEqual(listing.find(g=>g.id===pot.id).garden,{sequence:1,page:0,slot:0});
 const edit={signature:'Edited gardener',recipientName:'VJU teachers',message:'Thank you for helping us learn.',expected:{signature:'Original gardener',recipientName:'Teachers',message:'Thank you for teaching us.'}};
 for(const who of [null,'regular','expired'])assert.equal((await call(gardenPath+'/garden-edit',who,edit)).status,401);
 assert.equal((await call(gardenPath+'/garden-edit','owner',edit,'https://evil.test')).status,403);
 assert.equal((await call(gardenPath+'/garden-edit','owner',{...edit,status:'approved'})).status,400);
 assert.equal((await call(gardenPath+'/garden-edit','owner',{...edit,message:'x'})).status,400);
 assert.equal((await call(gardenPath+'/garden-edit','mod',edit)).status,200);
 assert.equal((await call(gardenPath+'/garden-edit','owner',edit)).status,409);
 let garden=(await call('/api/garden','regular')).data;
 assert.equal(garden.mine[0].message,edit.message);assert.equal(garden.mine[0].status,pot.status);assert.equal(garden.account.used,1);
 assert.equal((await call('/api/admin/greetings/'+card.id+'/garden-edit','owner',edit)).status,404);
 await call(gardenPath+'/moderate','owner',{action:'reject'});
 garden=(await call('/api/garden','regular')).data;assert.equal(garden.mine[0].status,'rejected');assert.equal(garden.published,0);
 grants=[];assert.equal((await call('/api/admin/greetings','owner')).status,401);
 assert.equal((await call(gardenPath+'/garden-edit','owner',edit)).status,401);
 assert.equal((await fetch(base+'/api/admin/greetings',{headers:{Authorization:'Bearer '+adminToken}})).status,200);
});
