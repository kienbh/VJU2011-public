import {readModerationRoles} from './moderationRoles.mjs';
import {mkdirSync,readFileSync,writeFileSync,existsSync} from 'node:fs';
import {randomBytes} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createAppServer} from './app.mjs';
import {runtimeConfig} from './runtimeConfig.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const {dataDir:local,port,...settings}=runtimeConfig(process.env,root);mkdirSync(local,{recursive:true,mode:0o700});
const manifestPath=path.join(root,'dist/release.json');
const manifest=existsSync(manifestPath)?JSON.parse(readFileSync(manifestPath,'utf8')):null;
if(settings.publicOrigin&&(!manifest||!/^[a-f0-9]{40}$/.test(manifest.sha)))throw Error('Public rehearsal requires npm run build:release from a clean commit.');
if(process.env.RELEASE_SHA&&process.env.RELEASE_SHA!==manifest?.sha)throw Error('RELEASE_SHA does not match the built artifact.');
const tokenPath=path.join(local,'admin-token.txt');
if(!existsSync(tokenPath))writeFileSync(tokenPath,randomBytes(32).toString('base64url'),{flag:'wx',mode:0o600});
const token=readFileSync(tokenPath,'utf8').trim();
const recipientsPath=path.join(local,'recipients.json');
const recipients=existsSync(recipientsPath)?JSON.parse(readFileSync(recipientsPath,'utf8')):[];
const ssoValues=['BCSE_ID_ISSUER','BCSE_ID_CLIENT_ID','BCSE_ID_CLIENT_SECRET','BCSE_ID_JWT_SECRET'].map(k=>process.env[k]);
if(ssoValues.some(Boolean)&&!ssoValues.every(Boolean))throw Error('Incomplete BCSE ID configuration.');
const ssoConfig=ssoValues.every(Boolean)?{issuer:ssoValues[0],clientId:ssoValues[1],clientSecret:ssoValues[2],jwtSecret:ssoValues[3],appOrigin:settings.publicOrigin||process.env.APP_URL}:null;
const server=createAppServer({dbPath:path.join(local,'vju2011.sqlite'),adminToken:token,moderationGrants:()=>readModerationRoles(path.join(local,'moderators.json')),recipients,...settings,ssoConfig,releaseSha:manifest?.sha||'development'});
server.listen(port,'127.0.0.1',()=>{console.log(`VJU2011 local rehearsal: http://127.0.0.1:${port}`);console.log('Isolated data directory configured; credentials are never printed. Submissions: '+(settings.submissionsEnabled?'test mode enabled':'locked off'));});
server.on('error',error=>{console.error(`Local server failed (${error.code||'SERVER_ERROR'}).`);process.exitCode=1;});
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>server.close(()=>{process.exitCode=0;}));
